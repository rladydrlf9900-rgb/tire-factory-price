/** 검색어 한 줄로 걸러내기 — 1756514 · 175/65R14 · 벤투스 다 받아준다 */
function 걸러내기(자료, 말, 제조사고름, 계절고름) {
  const s = (말 || '').trim().toLowerCase().replace(/\s+/g, '');
  const 숫자 = s.replace(/[^0-9]/g, '');
  return 자료.filter(r => {
    if (제조사고름 && 제조사고름.size && !제조사고름.has(r[0])) return false;
    if (계절고름 && 계절고름.size && !계절고름.has(r[5])) return false;
    if (!s) return true;
    const 규격숫자 = r[3].replace(/[^0-9]/g, '');
    if (숫자.length >= 3 && 규격숫자.startsWith(숫자)) return true;
    return (r[0] + r[1] + r[2] + r[3] + r[4]).toLowerCase().replace(/\s+/g, '').includes(s);
  });
}

/** DC율 칸이 바뀌면 할인가를 다시 적는다 (네 시안이 똑같이 쓴다) */
function DC묶기(뿌리) {
  뿌리.addEventListener('input', e => {
    const 칸 = e.target.closest('[data-dc]');
    if (!칸) return;
    const 줄 = 칸.closest('[data-row]');
    const 원가 = +줄.dataset.price;
    let dc = parseFloat(칸.value);
    if (isNaN(dc) || dc < 0) dc = 0;
    if (dc > 95) { dc = 95; 칸.value = 95; }
    const 값 = Math.round(원가 * (1 - dc / 100));
    줄.querySelector('[data-sale]').textContent = 돈(값);
    줄.classList.toggle('할인중', dc > 0);
  });
}
